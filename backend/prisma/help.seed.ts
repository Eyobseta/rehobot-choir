export async function seedHelpEntries(prisma: PrismaClient): Promise<number> {
  let count = 0;
  for (const e of ENTRIES) {
    await prisma.helpEntry.upsert({
      where: { slug: e.slug },
      create: {
        slug: e.slug,
        category: e.category,
        intentsEn: e.intentsEn,
        intentsAm: e.intentsAm,
        questionVariantsEn: e.questionVariantsEn,
        questionVariantsAm: e.questionVariantsAm,
        answerEn: e.answerEn,
        answerAm: e.answerAm,
        deepLink: e.deepLink,
        visibleToRoles: e.visibleToRoles,
        screenHints: e.screenHints,
        sortOrder: e.sortOrder,
        active: true,
      },
      update: {
        category: e.category,
        intentsEn: e.intentsEn,
        intentsAm: e.intentsAm,
        questionVariantsEn: e.questionVariantsEn,
        questionVariantsAm: e.questionVariantsAm,
        answerEn: e.answerEn,
        answerAm: e.answerAm,
        deepLink: e.deepLink,
        visibleToRoles: e.visibleToRoles,
        screenHints: e.screenHints,
        sortOrder: e.sortOrder,
        active: true,
      },
    });
    count++;
  }
  return count;
}