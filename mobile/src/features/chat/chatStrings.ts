let registered = false;
function ensureRegistered(): void {
  if (registered || !i18n.isInitialized) return;
  i18n.addResourceBundle('en', 'translation', { chat: chatEn }, true, true);
  i18n.addResourceBundle('am', 'translation', { chat: chatAm }, true, true);
  registered = true;
}

export type TrKey = keyof typeof chatEn;
export type Tr = (key: TrKey, opts?: Record<string, unknown>) => string;

/** Translate a chat string: tr('send'), tr('typingNamed', { name }). */
export function useTr(): Tr {
  const { t } = useTranslation();
  ensureRegistered();
  return useCallback(
    (key, opts) =>
      t(`chat.${key}`, { defaultValue: chatEn[key], ...(opts ?? {}) }) as string,
    [t],
  );
}
